from sensors.gps import GPS
from datetime import datetime
import json

class EventLocator:
    """
    V1 Localization Module: Uses standalone GPS to attach location to events.
    """
    def __init__(self, mode="SIMULATION"):
        self.gps_sensor = GPS(mode=mode)
        print("Initialized EventLocator (V1: Standalone GPS).")

    def attach_location(self, event_data: dict) -> dict:
        """
        1. Obtains latitude and longitude from the GPS sensor.
        2. Attaches the location to the event payload.
        """
        gps_data = self.gps_sensor.read_gps()
        
        event_data["latitude"] = gps_data["latitude"]
        event_data["longitude"] = gps_data["longitude"]
        event_data["location_source"] = "GPS"
        event_data["location_timestamp"] = datetime.now().isoformat()
        
        print(f"Attached location to event: Lat {gps_data['latitude']}, Lon {gps_data['longitude']}")
        return event_data

    def store_in_database(self, event_data: dict):
        """
        Takes the localized event and simulates writing the geometry to the HazardEvent DB table.
        """
        lat = event_data.get("latitude")
        lon = event_data.get("longitude")
        
        # WKT (Well-Known Text) format required by GeoAlchemy2
        wkt_point = f"POINT({lon} {lat})"
        
        # In a real environment, this connects to SQLAlchemy Session:
        # new_event = HazardEvent(
        #     name=event_data.get("event_type"),
        #     severity=event_data.get("severity"),
        #     geom=WKTElement(wkt_point, srid=4326),
        #     start_time=datetime.now()
        # )
        # db.add(new_event); db.commit()
        
        print("\n[DATABASE_MOCK] Storing Localized Event in DB...")
        print(f"INSERT INTO hazard_events (name, severity, geom) VALUES ('{event_data.get('event_type')}', '{event_data.get('severity')}', ST_GeomFromText('{wkt_point}', 4326));")
        print("Save successful.\n")
        return True

